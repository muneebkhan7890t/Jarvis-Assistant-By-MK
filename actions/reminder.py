def _schedule_windows(target_dt: datetime, task_name: str,
                      script_path: Path, message: str) -> str:
    python_exe = Path(sys.executable)
    pythonw = python_exe.parent / "pythonw.exe"
    if pythonw.exists():
        python_exe = pythonw

    xml_path = _scripts_dir() / f"{task_name}.xml"
    xml_content = (
        '<?xml version="1.0" encoding="UTF-16"?>\n'
        '<Task version="1.2" xmlns="http://schemas.microsoft.com/windows/2004/02/mit/task">\n'
        '  <RegistrationInfo><Description>J.A.R.V.I.S Reminder</Description></RegistrationInfo>\n'
        '  <Triggers><TimeTrigger>\n'
        f'    <StartBoundary>{target_dt.strftime("%Y-%m-%dT%H:%M:%S")}</StartBoundary>\n'
        '    <Enabled>true</Enabled>\n'
        '  </TimeTrigger></Triggers>\n'
        '  <Actions><Exec>\n'
        f'    <Command>{escape(str(python_exe))}</Command>\n'
        f'    <Arguments>"{escape(str(script_path))}"</Arguments>\n'
        '  </Exec></Actions>\n'
        '  <Settings>\n'
        '    <MultipleInstancesPolicy>IgnoreNew</MultipleInstancesPolicy>\n'
        '    <DisallowStartIfOnBatteries>false</DisallowStartIfOnBatteries>\n'
        '    <StopIfGoingOnBatteries>false</StopIfGoingOnBatteries>\n'
        '    <StartWhenAvailable>true</StartWhenAvailable>\n'
        '    <ExecutionTimeLimit>PT5M</ExecutionTimeLimit>\n'
        '    <Enabled>true</Enabled>\n'
        '  </Settings>\n'
        '  <Principals><Principal>\n'
        '    <LogonType>InteractiveToken</LogonType>\n'
        '    <RunLevel>LeastPrivilege</RunLevel>\n'
        '  </Principal></Principals>\n'
        '</Task>'
    )

    xml_path.write_text(xml_content, encoding="utf-16")

    result = subprocess.run(
        ["schtasks", "/Create", "/TN", task_name, "/XML", str(xml_path), "/F"],
        capture_output=True, text=True, timeout=30, **_CNW,
    )

    try:
        xml_path.unlink(missing_ok=True)
    except Exception:
        pass

    if result.returncode != 0:
        script_path.unlink(missing_ok=True)
        err = (result.stderr or result.stdout).strip()
        print(f"[Reminder] ❌ schtasks: {err}")
        return ""  

    return task_name


def _schedule_mac(target_dt: datetime, task_name: str,
                  script_path: Path) -> str:
    agents_dir = Path.home() / "Library" / "LaunchAgents"
    agents_dir.mkdir(parents=True, exist_ok=True)

    label     = f"com.jarvis.reminder.{task_name}"
    plist_path = agents_dir / f"{label}.plist"

    # plistlib escapes paths correctly, including ampersands in user directories.
    payload = {
        'Label': label, 'ProgramArguments': [sys.executable, str(script_path)],
        'StartCalendarInterval': {'Month': target_dt.month, 'Day': target_dt.day,
                                  'Hour': target_dt.hour, 'Minute': target_dt.minute},
        'RunAtLoad': False, 'StandardOutPath': '/dev/null', 'StandardErrorPath': '/dev/null',
    }
    plist_path.write_bytes(plistlib.dumps(payload))
    plist_path.chmod(0o644)

    result = subprocess.run(
        ["launchctl", "load", str(plist_path)],
        capture_output=True, text=True, timeout=30,
    )

    if result.returncode != 0:
        plist_path.unlink(missing_ok=True)
        script_path.unlink(missing_ok=True)
        print(f"[Reminder] ❌ launchctl: {result.stderr.strip()}")
        return ""

    return label


def _schedule_linux(target_dt: datetime, task_name: str,
                    script_path: Path) -> str:

    if shutil.which("systemd-run"):
        on_calendar = target_dt.strftime("%Y-%m-%d %H:%M:%S")
        result = subprocess.run(
            [
                "systemd-run",
                "--user",
                f"--on-calendar={on_calendar}",
                f"--unit={task_name}",
                "--",
                sys.executable, str(script_path),
            ],
            capture_output=True, text=True, timeout=30,
        )
        if result.returncode == 0:
            return task_name
        print(f"[Reminder] ⚠️ systemd-run failed: {result.stderr.strip()}, trying 'at'")

    if shutil.which("at"):
        at_time = target_dt.strftime("%H:%M %Y-%m-%d")
        cmd_str = f"{shlex.quote(sys.executable)} {shlex.quote(str(script_path))}\n"
        result  = subprocess.run(
            ["at", at_time],
            input=cmd_str, capture_output=True, text=True, env={**os.environ, "LC_ALL": "C"}, timeout=30,
        )
        if result.returncode == 0:
            match = re.search(r"job (\d+)", result.stderr + result.stdout)
            return "at:" + match[1] if match else task_name

        print(f"[Reminder] ❌ at: {result.stderr.strip()}")
        return ""

    print("[Reminder] ❌ Neither systemd-run nor at found on this Linux system.")
    return ""

def register_persistent(row):
    """Use the existing platform schedulers; generated scripts read current state."""
    task_name = f"JARVISReminder_{row['id']}_{row['generation']}"
    os_name = _get_os()
    target = datetime.fromisoformat(row['due_at']).astimezone().replace(tzinfo=None)
    script = _write_notify_script(task_name, row['message'], os_name,
                                  reminder_id=row['id'], generation=row['generation'])
    try:
        if os_name == 'windows':
            native = _schedule_windows(target, task_name, script, row['message'])
        elif os_name == 'mac':
            native = _schedule_mac(target, task_name, script)
        else:
            native = _schedule_linux(target, task_name, script)
        if not native:
            raise RuntimeError('Native scheduler registration failed.')
        return native, os_name
    except Exception:
        script.unlink(missing_ok=True)
        raise


def cancel_native(row):
    native, backend = row['native_id'], row['backend']
    if native.startswith('at:') and re.fullmatch(r'at:\d+', native):
        argv = ['atrm', native.split(':')[1]]
    elif backend == 'windows' and re.fullmatch(r'JARVISReminder_[0-9a-f]{32}_\d+', native):
        argv = ['schtasks', '/Delete', '/TN', native, '/F']
    elif backend == 'mac' and re.fullmatch(r'com.jarvis.reminder.JARVISReminder_[0-9a-f]{32}_\d+', native):
        target = Path.home() / 'Library' / 'LaunchAgents' / (native + '.plist')
        result = subprocess.run(['launchctl', 'unload', str(target)], capture_output=True, timeout=30)
        target.unlink(missing_ok=True)
        return '' if result.returncode == 0 else 'Native entry cleanup failed; its stored generation is disabled.'
    elif backend == 'linux' and re.fullmatch(r'JARVISReminder_[0-9a-f]{32}_\d+', native):
        argv = ['systemctl', '--user', 'stop', native + '.timer', native + '.service']
    else:
        return 'Native entry identifier is unrecognized; its stored generation is disabled.'
    result = subprocess.run(argv, capture_output=True, timeout=30, **_CNW)
    return '' if result.returncode == 0 else 'Native entry cleanup failed; its stored generation is disabled.'


def notify_local(message):
    """True means the notification backend accepted it, not that the user read it."""
    if _get_os() == 'windows':
        try:
            from win10toast import ToastNotifier
            result = ToastNotifier().show_toast('JARVIS Reminder', message, duration=10, threaded=False)
            if result is not False:
                return True
        except Exception:
            # Windows versions without a toast backend still support msg.exe.
            import logging
            logging.getLogger(__name__).info('Toast backend unavailable; trying native message notification')
        return subprocess.run(['msg', '*', '/TIME:30'], input=message, text=True, capture_output=True, timeout=35, **_CNW).returncode == 0
    elif _get_os() == 'mac':
        # Pass content as an argument to AppleScript, never interpolate executable source.
        program = 'on run argv\ndisplay notification (item 1 of argv) with title "JARVIS Reminder"\nend run'
        argv = ['osascript', '-e', program, '--', message]
    else:
        argv = ['notify-send', '--', 'JARVIS Reminder', message]
    return subprocess.run(argv, capture_output=True, timeout=35, **_CNW).returncode == 0


def reminder(parameters, response=None, player=None, session_memory=None):
    from core import reminders
    if not isinstance(parameters, dict):
        return 'Reminder parameters must be an object.'
    action = parameters.get('action', 'add')
    try:
        if action == 'list':
            return json.dumps(reminders.list_reminders(parameters.get('status', 'pending')), ensure_ascii=False)
        if action == 'history':
            return json.dumps(reminders.history(parameters.get('id', '')), ensure_ascii=False)
        due = None
        if action == 'add' or 'date' in parameters or 'time' in parameters:
            due = datetime.strptime(parameters.get('date', '') + ' ' + parameters.get('time', ''), '%Y-%m-%d %H:%M')
        if action == 'add':
            row = reminders.add(parameters.get('message', ''), due, parameters.get('repeat', 'none'))
            return f"Reminder set for {due:%B %d at %I:%M %p}. ID: {row['id']}. Repeat: {row['recurrence']}."
        if action in ('edit', 'cancel', 'complete', 'snooze'):
            row = reminders.change(parameters.get('id', ''), action, due=due,
                message=parameters.get('message'), recurrence=parameters.get('repeat'),
                minutes=parameters.get('minutes', 20), expected_generation=parameters.get('generation'))
            return f"Reminder {row['id']}: {row['state']}." + (' ' + row['cleanup_warning'] if row.get('cleanup_warning') else '')
        return 'Unknown reminder action.'
    except (ValueError, TypeError, RuntimeError, OSError, sqlite3.Error) as exc:
        return f'Reminder action failed: {exc}'


